/**
  ******************************************************************************
  * @file    Dac.h
  * @brief   DAC 模拟输出模块（PA4 输出正比于 RMS 的直流，头文件）
  ******************************************************************************
  * 这是这台"功率计"的模拟表盘：把一个 0~1 的归一化 RMS 直接映射成
  * 0~3.3 V 的直流电压，拿万用表量就能读数，不需要电脑。
  *
  * 换算关系（推导见 Sample.h 的归一化说明）：
  *   DAC 输出电压 = 归一化 RMS × 3.3 V = 输入 Vrms × 2
  *   所以反过来：输入 Vrms = PA4 电压 ÷ 2
  *
  *   满幅正弦（峰峰 3.3 V）→ RMS=0.707 → 输出 2.33 V
  *   满幅方波（0↔3.3 V）  → RMS=1.000 → 输出 3.30 V
  *
  * 硬件：PA4 = DAC1_OUT1（芯片内部固定，不能换脚）。
  *       注意 DISC1 上 PA4 也连着音频芯片 CS43L22 的 LRCK，
  *       本工程不初始化 I2S3，所以不冲突。
  ******************************************************************************
  */

/* Define to prevent recursive inclusion -------------------------------------*/
#ifndef __DAC_H
#define __DAC_H

/* Includes ------------------------------------------------------------------*/
#include "stm32f4xx.h"

/* 归一化 RMS 的满量程：1.0 表示"满幅方波"，对应 DAC 输出 3.3 V */
#define DAC_RMS_FULL_SCALE      1.0f

/* 满量程的倒数。改成乘法省一次除法（将来如果把满量程改成别的值也照样成立）。 */
#define DAC_RMS_INV_FULL_SCALE  (1.0f / DAC_RMS_FULL_SCALE)

/* 12 位 DAC 满码 */
#define DAC_MAX_CODE            4095.0f

/* Exported functions ------------------------------------------------------- */

/**
  * @brief  初始化 DAC1 通道 1（PA4），软件触发、输出缓冲打开
  * @param  None
  * @retval None
  * @note   初始化后输出 0 V，调用 Dac_SetRms() 才开始有电压。
  */
void Dac_Init(void);

/**
  * @brief  按归一化 RMS 设置输出电压
  * @param  rms 归一化 RMS，0~1（超出会被钳到范围内）
  * @retval None
  * @note   内部做了钳位，传进来的值乱掉也不会输出非法码。
  *         调用频率建议跟 CSV 上报同样节奏（约 94 Hz），不用更密。
  */
void Dac_SetRms(float rms);

#endif /* __DAC_H */
