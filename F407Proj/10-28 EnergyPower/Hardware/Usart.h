/**
  ******************************************************************************
  * @file    Usart.h
  * @brief   串口上传模块（USART2 + DMA 发送，头文件）
  ******************************************************************************
  * 为什么用 DMA 发：一行 CSV 约 64~72 字节，115200 波特率下用阻塞方式要占
  * 5~6 ms，主循环会被它拖住一半。改成 DMA 之后，CPU 只管把数据塞进缓冲，
  * 搬运交给硬件，发完再进一次中断，几乎不占时间。
  *
  * ★ 带宽核算（这一项决定你会不会丢行，务必自己算一遍）：
  *   115200 8N1 的可用带宽 = 115200 / 10 = 11520 字节/秒。
  *   每块 DMA 数据 = 256 点，块时长 = 256 / 采样率。
  *   行宽实测随能量值变长：开机 64 B，跑 1 小时约 72 B（E 变成 8 位数）。
  *
  *     fs=48k, 2 块/行 → 10.67 ms/行 → 93.8 行/s × 72 B = 6750 B/s → 占 59%  ✓
  *     fs=48k, 1 块/行 →  5.33 ms/行 → 187.5 行/s × 72 B = 13500 B/s → 117%  ✗ 必丢
  *     fs=96k, 2 块/行 →  5.33 ms/行 → 187.5 行/s × 72 B = 13500 B/s → 117%  ✗ 必丢
  *     fs=96k, 4 块/行 → 10.67 ms/行 → 93.8 行/s × 72 B = 6750 B/s → 59%   ✓
  *
  *   所以改采样率的时候，SAMPLE_TX_BLOCKS 要跟着一起改，别只改一个。
  *   丢行的判断在 Usart_SendLine 里：忙就直接丢这一行，不阻塞主循环。
  *
  * 接法（两种都行，代码完全一样）：
  *   A. 板载 ST-LINK 虚拟串口：一根 USB 线插板子的 USB 口即可，
  *      PA2/PA3 已经在板内连到 ST-LINK 了，PC 上出现 STMicroelectronics
  *      Virtual COM Port。
  *   B. 外接 CH340 模块：
  *      F407 PA2 (TX) → CH340 RXD
  *      F407 PA3 (RX) → CH340 TXD
  *      GND ↔ GND（一定要共地）
  *      PC 上出现 USB-SERIAL CH340。
  ******************************************************************************
  */

/* Define to prevent recursive inclusion -------------------------------------*/
#ifndef __USART_H
#define __USART_H

/* Includes ------------------------------------------------------------------*/
#include "stm32f4xx.h"

/* 串口参数 ------------------------------------------------------------------*/

/* 波特率，单位: bps。115200 是板载 VCP 和 CH340 都稳的值。
   外接 CH340 的话可以提到 230400 / 460800 来提高刷新率
   （但板载 ST-LINK 虚拟串口不一定支持那么高，会收到乱码）。 */
#define USART_BAUD_HZ       115200U

/* 单行缓冲长度，单位: 字节。
   最长的一行是 E 涨到 8 位数时，约 72 字节；开机短一些约 64。
   留到 128 有充分余量，同时两块缓冲只占 256 字节 RAM。 */
#define USART_LINE_MAX      128U

/* Exported functions ------------------------------------------------------- */

/**
  * @brief  初始化 USART2（PA2/PA3）和它的 DMA 发送通道
  * @param  None
  * @retval None
  * @note   115200 8N1，无流控。DMA 用 DMA1_Stream6 / Channel4（USART2_TX 固定映射）。
  *         同时开 TC（发送完成）和 TE（传输出错）两个中断 —— TE 是必需的，
  *         否则一次总线错误会让 DMA 流被硬件关掉而 TC 永远不来，
  *         串口就永久哑掉且没有任何提示。
  */
void Usart_Init(void);

/**
  * @brief  发一行字符串（非阻塞，交给 DMA 搬）
  * @param  str  要发送的内容，调用返回后这块内存就可以复用
  * @param  len  字节数，超过 USART_LINE_MAX 会被截断
  * @retval 1 = 已经启动发送；0 = 上一包还没发完，这次丢弃
  * @note   返回 0 说明串口带宽不够或者波特率太低，可以加大
  *         SAMPLE_TX_BLOCKS 或提高 USART_BAUD_HZ。
  *         内部等 DMA 流关闭的操作带超时保护，不会把主循环卡死。
  */
uint8_t Usart_SendLine(const char *str, uint16_t len);

/**
  * @brief  DMA 中断处理片段：清标志 + 释放缓冲（含传输出错恢复）
  * @param  None
  * @retval None
  * @note   只能由 main.c 里的 DMA1_Stream6_IRQHandler() 调用。
  */
void Usart_IsrHandler(void);

#endif /* __USART_H */
